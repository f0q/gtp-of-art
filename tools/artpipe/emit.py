def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    txt = json.dumps(obj, indent=1, ensure_ascii=False, sort_keys=False) + "\n"
    if not path.exists() or path.read_text() != txt:
        path.write_text(txt)


def credits(artworks: list[dict], generated_at: str) -> dict:
    imgs, prices = [], []
    for a in artworks:
        im = a["images"]["primary"]
        imgs.append({"artwork_id": a["id"], "title": a["title"], "artist": a["artist"]["display_name"],
                     "licence": im["licence"], "attribution": im["attribution"],
                     "landing_url": im["landing_url"], "source_url": im.get("source_url")})
        for p in a["prices"]:
            prices.append({"artwork_id": a["id"], "price_id": p["id"], "source_urls": p["source_urls"],
                           "verified_by": p.get("verified_by")})
    return {"generated_at": generated_at, "disclaimer": DISCLAIMER, "data_sources": DATA_SOURCES,
            "images": imgs, "price_sources": prices,
            "copy": "All teasers, alt text and category teaching copy are original to this project."}


def credits_md(c: dict) -> str:
    out = ["# Credits", "", "_Generated by tools/build_dataset.py — do not edit by hand._", "",
           "## Disclaimer", "", c["disclaimer"], "", "## Data sources", ""]
    for s in c["data_sources"]:
        out.append(f"- [{s['name']}]({s['url']}) — {s['licence']}")
    out += ["", "## Images", "", "| Work | Artist | Licence | Attribution |", "|---|---|---|---|"]
    for i in c["images"]:
        t = i["title"].replace("|", "/")
        out.append(f"| [{t}]({i['landing_url']}) | {i['artist']} | {i['licence']} | {i['attribution'].replace('|', '/')} |")
    out += ["", "## Price sources", ""]
    for p in c["price_sources"]:
        links = " · ".join(f"<{u}>" for u in p["source_urls"]) or "(none)"
        out.append(f"- `{p['price_id']}`: {links}")
    out += ["", c["copy"], ""]
    return "\n".join(out)


def _thumb_b64(path: str) -> str:
    im = Image.open(path)
    im.thumbnail((260, 260))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=70)
    return base64.b64encode(buf.getvalue()).decode()


def fmt_usd(x: int) -> str:
    for unit, s in ((1e9, "B"), (1e6, "M"), (1e3, "K")):
        if x >= unit:
            return f"${x / unit:.3g}{s}"
    return f"${x}"


def report_html(artworks: list[dict], masters: dict[str, str], vreport, stats: dict) -> str:
    rows = []
    for a in artworks:
        im = a["images"]["primary"]
        gp = next((p for p in a["prices"] if p["id"] == a["game_price_id"]), None)
        price = (f"{fmt_usd(gp['usd_nominal'])} ({gp['date'][:4]}) · adj {fmt_usd(gp['usd_adjusted'])} · "
                 f"{gp['type']} · {gp['confidence']} · {gp['price_scope']}") if gp else "unpriced pool"
        flags = []
        if im.get("lg_missing"):
            flags.append("lg_missing")
        b64 = _thumb_b64(masters[a["id"]]) if a["id"] in masters else ""
        sw = "".join(f'<span class="sw" style="background:{h}"></span>' for h in im.get("palette", []))
        t = a["taste"]
        rows.append(f"""<figure><img src="data:image/jpeg;base64,{b64}" alt="{html.escape(im['alt_text'])}">
<figcaption><b>{html.escape(a['title'])}</b><br>{html.escape(a['artist']['display_name'])}, {html.escape(a['date']['display'])}
<br><code>{a['id']}</code> · {a['category_id']}<br>{html.escape(price)}
<br>{im['licence']} · {html.escape(im['attribution'][:90])}<br>{sw}
<br><small>{t['subject']} · {t['mood']} · abs {t['abstraction']} warm {t['warmth']} sat {t['saturation']} bri {t['brightness']} cx {t['complexity']}</small>
{('<br><em>' + ', '.join(flags) + '</em>') if flags else ''}</figcaption></figure>""")
    errs = "".join(f"<li>{html.escape(e)}</li>" for e in vreport.errors) or "<li>none</li>"
    warns = "".join(f"<li>{html.escape(w)}</li>" for w in vreport.warnings) or "<li>none</li>"
    st = html.escape(json.dumps(stats, indent=1))
